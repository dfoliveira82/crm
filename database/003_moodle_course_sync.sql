/* Estado local da integração RM -> Moodle. Executar uma vez no banco do CRM. */
IF OBJECT_ID(N'dbo.CRM_MOODLE_COURSE_SYNC', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CRM_MOODLE_COURSE_SYNC
    (
        ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_CRM_MOODLE_COURSE_SYNC PRIMARY KEY,
        RM_IDNUMBER VARCHAR(250) NOT NULL,
        MOODLE_COURSE_ID INT NULL,
        STATUS VARCHAR(20) NOT NULL CONSTRAINT DF_CRM_MOODLE_COURSE_SYNC_STATUS DEFAULT 'PENDENTE',
        LAST_SYNC_AT DATETIME2(3) NULL,
        LAST_ERROR NVARCHAR(MAX) NULL,
        CREATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_CRM_MOODLE_COURSE_SYNC_CREATED DEFAULT SYSDATETIME(),
        UPDATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_CRM_MOODLE_COURSE_SYNC_UPDATED DEFAULT SYSDATETIME(),
        CONSTRAINT UQ_CRM_MOODLE_COURSE_SYNC_RM_IDNUMBER UNIQUE (RM_IDNUMBER),
        CONSTRAINT CK_CRM_MOODLE_COURSE_SYNC_STATUS CHECK (STATUS IN ('PENDENTE', 'INTEGRADA', 'ERRO'))
    );

    CREATE INDEX IX_CRM_MOODLE_COURSE_SYNC_STATUS
        ON dbo.CRM_MOODLE_COURSE_SYNC (STATUS);
END;
