/* Diagnostico dos codigos encontrados na instalacao RM. Somente leitura. */
SELECT 'FLAN' AS ORIGEM, CAST(PAGREC AS varchar(20)) AS CODIGO_1,
       CAST(STATUSLAN AS varchar(20)) AS CODIGO_2, COUNT_BIG(*) AS QUANTIDADE
FROM dbo.FLAN
WHERE DATACRIACAO >= DATEADD(MONTH, -12, GETDATE())
GROUP BY PAGREC, STATUSLAN
UNION ALL
SELECT 'FLANBAIXA' AS ORIGEM, CAST(STATUS AS varchar(20)) AS CODIGO_1,
       CAST(TIPOBAIXA AS varchar(20)) AS CODIGO_2, COUNT_BIG(*) AS QUANTIDADE
FROM dbo.FLANBAIXA
WHERE DATABAIXA >= DATEADD(MONTH, -12, GETDATE())
   OR DATACANCELBAIXA >= DATEADD(MONTH, -12, GETDATE())
GROUP BY STATUS, TIPOBAIXA
ORDER BY ORIGEM, CODIGO_1, CODIGO_2;
