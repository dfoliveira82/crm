/*
    Cadastro facial local do SGU.
    O navegador gera descritores Float32 de 128 posições (512 bytes cada).
    O SQL Server guarda somente os descritores, nunca uma fotografia.
*/

IF OBJECT_ID(N'dbo.PONTO_FACIAL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.PONTO_FACIAL
    (
        IDPONTOFACIAL BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PONTO_FACIAL PRIMARY KEY,
        CODCOLIGADA INT NOT NULL,
        CHAPA VARCHAR(30) NOT NULL,
        CPF VARCHAR(11) NOT NULL,
        DESCRITORES VARBINARY(MAX) NOT NULL,
        DESCRITOR_COUNT TINYINT NOT NULL,
        STATUS VARCHAR(20) NOT NULL CONSTRAINT DF_PONTO_FACIAL_STATUS DEFAULT 'ATIVO',
        CREATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_PONTO_FACIAL_CREATED DEFAULT SYSDATETIME(),
        UPDATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_PONTO_FACIAL_UPDATED DEFAULT SYSDATETIME(),
        CONSTRAINT UQ_PONTO_FACIAL_FUNCIONARIO UNIQUE (CODCOLIGADA, CHAPA),
        CONSTRAINT CK_PONTO_FACIAL_STATUS CHECK (STATUS IN ('ATIVO', 'INATIVO')),
        CONSTRAINT CK_PONTO_FACIAL_COUNT CHECK (DESCRITOR_COUNT BETWEEN 1 AND 3)
    );

    CREATE INDEX IX_PONTO_FACIAL_CPF ON dbo.PONTO_FACIAL (CPF);
    PRINT 'Tabela dbo.PONTO_FACIAL criada para reconhecimento facial local.';
END
ELSE
BEGIN
    PRINT 'A tabela dbo.PONTO_FACIAL já existe. Para instalações que vieram da versão AWS, execute 003_migrar_ponto_facial_local.sql.';
END
