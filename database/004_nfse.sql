GO

IF OBJECT_ID('dbo.NFS_LOG', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_LOG (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_LOG PRIMARY KEY,
        NIVEL               VARCHAR(15) NOT NULL,
        ORIGEM              VARCHAR(80) NOT NULL,
        MENSAGEM            NVARCHAR(2000) NOT NULL,
        CONTEXTO            NVARCHAR(MAX) NULL,
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_LOG_CRIACAO DEFAULT (SYSDATETIME())
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_NFS_FILA_STATUS_DATA' AND object_id = OBJECT_ID('dbo.NFS_FILA'))
    CREATE INDEX IX_NFS_FILA_STATUS_DATA ON dbo.NFS_FILA (STATUS, DT_CRIACAO DESC);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_NFS_COBRANCA_COLIGADA_ELEGIVEL' AND object_id = OBJECT_ID('dbo.NFS_COBRANCA'))
    CREATE INDEX IX_NFS_COBRANCA_COLIGADA_ELEGIVEL ON dbo.NFS_COBRANCA (CODCOLIGADA, ELEGIVEL_EMISSAO, QUITADA_INTEGRAL);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_NFS_BAIXAS_COBRANCA' AND object_id = OBJECT_ID('dbo.NFS_BAIXAS'))
    CREATE INDEX IX_NFS_BAIXAS_COBRANCA ON dbo.NFS_BAIXAS (ID_COBRANCA, DATA_BAIXA);
GO
PRINT 'Estrutura NFS-e criada/verificada com sucesso.';
GO
