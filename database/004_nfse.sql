GO

IF OBJECT_ID('dbo.NFS_EVENTO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_EVENTO (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_EVENTO PRIMARY KEY,
        ID_COBRANCA         BIGINT NOT NULL,
        ID_FILA             BIGINT NULL,
        TIPO                VARCHAR(50) NOT NULL,
        DESCRICAO           NVARCHAR(1500) NOT NULL,
        USUARIO             VARCHAR(120) NULL,
