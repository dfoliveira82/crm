        XML_ENVIO           NVARCHAR(MAX) NULL,
        XML_RETORNO         NVARCHAR(MAX) NULL,
        URL_PDF             NVARCHAR(1000) NULL,
        PROTOCOLO           VARCHAR(120) NULL,
        DT_EMISSAO          DATETIME2(0) NULL,
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_DOC_CRIACAO DEFAULT (SYSDATETIME()),
        CONSTRAINT FK_NFS_DOC_COBRANCA FOREIGN KEY (ID_COBRANCA) REFERENCES dbo.NFS_COBRANCA(ID),
