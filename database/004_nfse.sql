SET NOCOUNT ON;
GO

IF OBJECT_ID('dbo.NFS_CONFIG', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_CONFIG (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_CONFIG PRIMARY KEY,
        CODCOLIGADA         INT NOT NULL,
        AMBIENTE            VARCHAR(20) NOT NULL CONSTRAINT DF_NFS_CONFIG_AMBIENTE DEFAULT ('HOMOLOGACAO'),
        REGIME_TRIBUTARIO   VARCHAR(40) NULL,
        INSCRICAO_MUNICIPAL VARCHAR(30) NULL,
        CNPJ_PRESTADOR      VARCHAR(14) NULL,
        CODIGO_MUNICIPIO    VARCHAR(7) NULL,
        ATIVO               BIT NOT NULL CONSTRAINT DF_NFS_CONFIG_ATIVO DEFAULT (0),
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_CONFIG_CRIACAO DEFAULT (SYSDATETIME()),
        DT_ATUALIZACAO      DATETIME2(0) NULL,
        CONSTRAINT UQ_NFS_CONFIG_COLIGADA UNIQUE (CODCOLIGADA),
        CONSTRAINT CK_NFS_CONFIG_AMBIENTE CHECK (AMBIENTE IN ('HOMOLOGACAO','PRODUCAO'))
    );
END;
GO

IF OBJECT_ID('dbo.NFS_SERVICOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_SERVICOS (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_SERVICOS PRIMARY KEY,
        CODCOLIGADA         INT NOT NULL,
        CODIGO_SERVICO      VARCHAR(30) NOT NULL,
        DESCRICAO           VARCHAR(250) NOT NULL,
        ITEM_LISTA_SERVICO  VARCHAR(20) NULL,
        CNAE                VARCHAR(20) NULL,
        ALIQUOTA            DECIMAL(9,6) NULL,
        RETEM_ISS           BIT NOT NULL CONSTRAINT DF_NFS_SERVICOS_RETEM DEFAULT (0),
        ATIVO               BIT NOT NULL CONSTRAINT DF_NFS_SERVICOS_ATIVO DEFAULT (1),
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_SERVICOS_CRIACAO DEFAULT (SYSDATETIME()),
        CONSTRAINT UQ_NFS_SERVICOS UNIQUE (CODCOLIGADA, CODIGO_SERVICO)
    );
END;
GO

IF OBJECT_ID('dbo.NFS_COBRANCA', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_COBRANCA (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_COBRANCA PRIMARY KEY,
        CODCOLIGADA         INT NOT NULL,
        IDLAN_RM            VARCHAR(60) NOT NULL,
        CODCFO_RM           VARCHAR(60) NULL,
        NOME_TOMADOR        VARCHAR(200) NULL,
        DOCUMENTO_TOMADOR   VARCHAR(20) NULL,
        EMAIL_TOMADOR       VARCHAR(200) NULL,
        COMPETENCIA         VARCHAR(20) NULL,
        DATA_VENCIMENTO     DATE NULL,
        VALOR_ORIGINAL      DECIMAL(18,2) NOT NULL CONSTRAINT DF_NFS_COB_VALOR_ORIGINAL DEFAULT (0),
        VALOR_PAGO          DECIMAL(18,2) NOT NULL CONSTRAINT DF_NFS_COB_VALOR_PAGO DEFAULT (0),
        VALOR_DESCONTO      DECIMAL(18,2) NOT NULL CONSTRAINT DF_NFS_COB_VALOR_DESC DEFAULT (0),
        VALOR_JUROS         DECIMAL(18,2) NOT NULL CONSTRAINT DF_NFS_COB_VALOR_JUROS DEFAULT (0),
        VALOR_MULTA         DECIMAL(18,2) NOT NULL CONSTRAINT DF_NFS_COB_VALOR_MULTA DEFAULT (0),
        VALOR_SERVICO       DECIMAL(18,2) NULL,
        SALDO_RM            DECIMAL(18,2) NULL,
        QUITADA_INTEGRAL    BIT NOT NULL CONSTRAINT DF_NFS_COB_QUITADA DEFAULT (0),
        ELEGIVEL_EMISSAO    BIT NOT NULL CONSTRAINT DF_NFS_COB_ELEGIVEL DEFAULT (0),
        HASH_ORIGEM         CHAR(64) NULL,
        DT_ULTIMA_SINC      DATETIME2(0) NULL,
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_COB_CRIACAO DEFAULT (SYSDATETIME()),
        DT_ATUALIZACAO      DATETIME2(0) NULL,
        CONSTRAINT UQ_NFS_COBRANCA_RM UNIQUE (CODCOLIGADA, IDLAN_RM)
    );
END;
GO

IF OBJECT_ID('dbo.NFS_BAIXAS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_BAIXAS (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_BAIXAS PRIMARY KEY,
        ID_COBRANCA         BIGINT NOT NULL,
        CODCOLIGADA         INT NOT NULL,
        IDLAN_RM            VARCHAR(60) NOT NULL,
        IDBAIXA_RM          VARCHAR(60) NOT NULL,
        DATA_BAIXA          DATETIME2(0) NULL,
        VALOR_BAIXA         DECIMAL(18,2) NOT NULL,
        STATUS_RM           VARCHAR(40) NULL,
        ESTORNADA           BIT NOT NULL CONSTRAINT DF_NFS_BAIXAS_ESTORNADA DEFAULT (0),
        HASH_ORIGEM         CHAR(64) NULL,
        DT_SINC             DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_BAIXAS_SINC DEFAULT (SYSDATETIME()),
        CONSTRAINT FK_NFS_BAIXAS_COBRANCA FOREIGN KEY (ID_COBRANCA) REFERENCES dbo.NFS_COBRANCA(ID),
        CONSTRAINT UQ_NFS_BAIXAS_RM UNIQUE (CODCOLIGADA, IDLAN_RM, IDBAIXA_RM)
    );
END;
GO

IF OBJECT_ID('dbo.NFS_FILA', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_FILA (
        ID                  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_NFS_FILA PRIMARY KEY,
        ID_COBRANCA         BIGINT NOT NULL,
        STATUS              VARCHAR(40) NOT NULL CONSTRAINT DF_NFS_FILA_STATUS DEFAULT ('AGUARDANDO_CONFIGURACAO'),
        PRIORIDADE          TINYINT NOT NULL CONSTRAINT DF_NFS_FILA_PRIORIDADE DEFAULT (5),
        TENTATIVAS          INT NOT NULL CONSTRAINT DF_NFS_FILA_TENTATIVAS DEFAULT (0),
        CHAVE_IDEMPOTENCIA  CHAR(64) NOT NULL,
        MENSAGEM_STATUS     NVARCHAR(1000) NULL,
        DT_PROXIMA_TENTATIVA DATETIME2(0) NULL,
        DT_CRIACAO          DATETIME2(0) NOT NULL CONSTRAINT DF_NFS_FILA_CRIACAO DEFAULT (SYSDATETIME()),
        DT_ATUALIZACAO      DATETIME2(0) NULL,
        CONSTRAINT FK_NFS_FILA_COBRANCA FOREIGN KEY (ID_COBRANCA) REFERENCES dbo.NFS_COBRANCA(ID),
        CONSTRAINT UQ_NFS_FILA_COBRANCA UNIQUE (ID_COBRANCA),
        CONSTRAINT UQ_NFS_FILA_IDEMPOTENCIA UNIQUE (CHAVE_IDEMPOTENCIA),
        CONSTRAINT CK_NFS_FILA_STATUS CHECK (STATUS IN ('AGUARDANDO_CONFIGURACAO','AGUARDANDO_DADOS','PENDENTE_REVISAO','AGUARDANDO_AUTORIZACAO','AUTORIZADA','ENVIANDO','EMITIDA','ERRO','CANCELADA'))
    );
END;
GO

IF OBJECT_ID('dbo.NFS_DOCUMENTO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.NFS_DOCUMENTO (
