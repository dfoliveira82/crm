IF OBJECT_ID(N'dbo.CRM_CALENDAR_EVENTS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CRM_CALENDAR_EVENTS
    (
        ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_CRM_CALENDAR_EVENTS PRIMARY KEY,
        OWNER_CODE VARCHAR(100) NOT NULL,
        TITLE NVARCHAR(200) NOT NULL,
        STARTS_AT DATETIME2(0) NOT NULL,
        ENDS_AT DATETIME2(0) NOT NULL,
        LOCATION NVARCHAR(250) NULL,
        DESCRIPTION NVARCHAR(MAX) NULL,
        STATUS VARCHAR(20) NOT NULL CONSTRAINT DF_CRM_CALENDAR_EVENTS_STATUS DEFAULT 'ACTIVE',
        CREATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_CRM_CALENDAR_EVENTS_CREATED DEFAULT SYSDATETIME(),
        UPDATED_AT DATETIME2(3) NOT NULL CONSTRAINT DF_CRM_CALENDAR_EVENTS_UPDATED DEFAULT SYSDATETIME(),
        CONSTRAINT CK_CRM_CALENDAR_EVENTS_PERIOD CHECK (ENDS_AT > STARTS_AT),
        CONSTRAINT CK_CRM_CALENDAR_EVENTS_STATUS CHECK (STATUS IN ('ACTIVE', 'CANCELLED'))
    );

    CREATE INDEX IX_CRM_CALENDAR_EVENTS_OWNER_PERIOD
        ON dbo.CRM_CALENDAR_EVENTS (OWNER_CODE, STARTS_AT, ENDS_AT);
END;
